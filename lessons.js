// A wide underline is an answer slot. Each bookshop slot holds one punctuation mark.
function lineEnding(context, prompt, ending, choices, hint, explanation) {
  return {context, prompt, options: [ending, ...choices], answer: [ending], hint, explanation};
}

function simile(context, subject, link, image, hint, explanation) {
  return {
    context,
    options: [subject, link, image], answer: [subject, link, image], hint, explanation
  };
}

function voice(context, prompt, word, hint, explanation) {
  return {context, prompt, options: ['咦', '哼', '喂', '噢', '啊'], answer: [word], hint, explanation};
}

function punctuation(context, prompt, marks, hint, explanation) {
  return {context, prompt, options: ['！', '？', '：', '「', '」'], answer: [...marks], hint, explanation};
}

